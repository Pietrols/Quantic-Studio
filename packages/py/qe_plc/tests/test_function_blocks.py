"""Function blocks against handwritten scan traces (WP-2.8).

Every expected table below was written by hand from the block definitions in
docs/specs/structured-text-subset.md section 6 (Bolton, Programmable Logic
Controllers, 6th ed, 2015: timers section 9.1 p. 225 and Fig. 9.3 p. 226; counters
section 10.1 p. 245 and Fig. 10.1 p. 246; Beckhoff Tc2_Standard pages; marked subset
choices where the sources are silent), scan by scan
with a 100 ms period starting at t = 0. Nothing is generated by the code under test.
"""
from __future__ import annotations

from qe_plc import InputEvent, run_program

PERIOD = 100


def events(**columns):
    """Per-scan input values -> events at each scan's start time."""
    out = []
    for name, values in columns.items():
        for scan, value in enumerate(values):
            out.append(InputEvent(scan * PERIOD, name, bool(value) if isinstance(value, int) and value in (0, 1)
                                  and name not in ("N",) else value))
    return out


def trace(source, scans, **columns):
    result = run_program(source, period_ms=PERIOD, duration_ms=scans * PERIOD, events=events(**columns))
    assert result["status"] == "success", result["diagnostics"]
    return result["scans"]


def timer_program(kind, preset):
    return f"""PROGRAM T
VAR_INPUT IN1 : BOOL; END_VAR
VAR_OUTPUT Q1 : BOOL; E1 : TIME; END_VAR
VAR B : {kind}; END_VAR
B(IN := IN1, PT := T#{preset}ms);
Q1 := B.Q;
E1 := B.ET;
END_PROGRAM"""


def test_ton_handwritten_trace():
    # PT 300 ms. IN rises at 100 ms, so ET = t - 100 up to PT; Q at ET >= PT (t = 400).
    # IN false at 600 resets Q and ET; IN again from 700.
    IN = [0, 1, 1, 1, 1, 1, 0, 1, 1]
    ET = [0, 0, 100, 200, 300, 300, 0, 0, 100]
    Q = [0, 0, 0, 0, 1, 1, 0, 0, 0]
    scans = trace(timer_program("TON", 300), 9, IN1=IN)
    assert [s["outputs"]["E1"] for s in scans] == ET
    assert [s["outputs"]["Q1"] for s in scans] == [bool(q) for q in Q]


def test_tof_handwritten_trace():
    # PT 200 ms. Q follows IN to 1. IN falls at 300: Q stays 1 while ET < 200, drops at 500.
    # ET holds 200 until IN is true again at 700. IN falls at 800 and rises at 900.
    IN = [0, 1, 1, 0, 0, 0, 0, 1, 0, 1]
    Q = [0, 1, 1, 1, 1, 0, 0, 1, 1, 1]
    ET = [0, 0, 0, 0, 100, 200, 200, 0, 0, 0]
    scans = trace(timer_program("TOF", 200), 10, IN1=IN)
    assert [s["outputs"]["Q1"] for s in scans] == [bool(q) for q in Q]
    assert [s["outputs"]["E1"] for s in scans] == ET


def test_tp_handwritten_trace():
    # PT 300 ms. Rising IN at 100 starts the pulse; Q is 1 at 100, 200, 300 (ET 0, 100, 200) whatever IN
    # does, and 0 from 400 (ET 300). The rising IN at 300 during the pulse is ignored (not retriggerable).
    # ET holds 300 while IN stays true (400, 500) and returns to 0 at 600. New pulse at 700.
    IN = [0, 1, 0, 1, 1, 1, 0, 1, 1]
    Q = [0, 1, 1, 1, 0, 0, 0, 1, 1]
    ET = [0, 0, 100, 200, 300, 300, 0, 0, 100]
    scans = trace(timer_program("TP", 300), 9, IN1=IN)
    assert [s["outputs"]["Q1"] for s in scans] == [bool(q) for q in Q]
    assert [s["outputs"]["E1"] for s in scans] == ET


def test_zero_preset_timers():
    # PT 0: TON is on in the same scan IN is true; TP gives no pulse; TOF drops in the scan IN falls.
    scans = trace(timer_program("TON", 0), 3, IN1=[0, 1, 0])
    assert [s["outputs"]["Q1"] for s in scans] == [False, True, False]
    scans = trace(timer_program("TP", 0), 3, IN1=[0, 1, 1])
    assert [s["outputs"]["Q1"] for s in scans] == [False, False, False]
    scans = trace(timer_program("TOF", 0), 3, IN1=[1, 0, 0])
    assert [s["outputs"]["Q1"] for s in scans] == [True, False, False]


COUNTERS = """PROGRAM C
VAR_INPUT U, D, RST, LOAD : BOOL; END_VAR
VAR_OUTPUT CVU, CVD, CVUD : INT; QU1, QD1, QUD_U, QUD_D : BOOL; END_VAR
VAR CU1 : CTU; CD1 : CTD; UD : CTUD; END_VAR
CU1(CU := U, R := RST, PV := 3);
CD1(CD := D, LD := LOAD, PV := 2);
UD(CU := U, CD := D, R := RST, LD := LOAD, PV := 2);
CVU := CU1.CV; QU1 := CU1.Q;
CVD := CD1.CV; QD1 := CD1.Q;
CVUD := UD.CV; QUD_U := UD.QU; QUD_D := UD.QD;
END_PROGRAM"""


def test_ctu_handwritten_trace():
    # PV 3: each rising U adds 1; RST at scan 7 resets to 0 (reset wins); Q = CV >= 3.
    U = [0, 1, 1, 0, 1, 0, 1, 0, 1]
    RST = [0, 0, 0, 0, 0, 0, 0, 1, 0]
    CV = [0, 1, 1, 1, 2, 2, 3, 0, 1]
    Q = [0, 0, 0, 0, 0, 0, 1, 0, 0]
    scans = trace(COUNTERS, 9, U=U, D=[0] * 9, RST=RST, LOAD=[0] * 9)
    assert [s["outputs"]["CVU"] for s in scans] == CV
    assert [s["outputs"]["QU1"] for s in scans] == [bool(q) for q in Q]


def test_ctd_handwritten_trace():
    # PV 2: LOAD at scan 0 sets CV 2; rising D at scans 1 and 3 subtract 1; the rising D at scan 5
    # finds CV = 0 and counting has stopped (Bolton Fig. 10.1a, p. 246). Q = CV <= 0.
    D = [0, 1, 0, 1, 0, 1]
    LOAD = [1, 0, 0, 0, 0, 0]
    CV = [2, 1, 1, 0, 0, 0]
    Q = [0, 0, 0, 1, 1, 1]
    scans = trace(COUNTERS, 6, U=[0] * 6, D=D, RST=[0] * 6, LOAD=LOAD)
    assert [s["outputs"]["CVD"] for s in scans] == CV
    assert [s["outputs"]["QD1"] for s in scans] == [bool(q) for q in Q]


def test_ctud_handwritten_trace():
    # PV 2. Scan 0 rising U: 1. Scan 2 rising D: 0 (QD). Scan 3 rising U: 1. Scan 5 U and D rise together:
    # unchanged. Scan 6 LOAD: CV = PV = 2 (QU). Scan 7 RST and LOAD together: reset wins, 0 (QD).
    U = [1, 1, 0, 1, 0, 1, 0, 0]
    D = [0, 0, 1, 0, 0, 1, 0, 0]
    RST = [0, 0, 0, 0, 0, 0, 0, 1]
    LOAD = [0, 0, 0, 0, 0, 0, 1, 1]
    CV = [1, 1, 0, 1, 1, 1, 2, 0]
    QU = [0, 0, 0, 0, 0, 0, 1, 0]
    QD = [0, 0, 1, 0, 0, 0, 0, 1]
    scans = trace(COUNTERS, 8, U=U, D=D, RST=RST, LOAD=LOAD)
    assert [s["outputs"]["CVUD"] for s in scans] == CV
    assert [s["outputs"]["QUD_U"] for s in scans] == [bool(q) for q in QU]
    assert [s["outputs"]["QUD_D"] for s in scans] == [bool(q) for q in QD]


def test_ctud_up_saturates_at_int_max():
    source = """PROGRAM S
VAR_INPUT P : BOOL; END_VAR
VAR_OUTPUT V : INT; END_VAR
VAR C1 : CTUD; END_VAR
C1(CU := P, PV := 0);
V := C1.CV;
END_PROGRAM"""
    from qe_plc.scan import ScanEngine
    engine = ScanEngine(source, 10)
    engine.blocks["C1"].CV = 32767
    engine.scan({"P": True})
    assert engine.output_image["V"] == 32767  # no wrap to -32768 (choice)


def test_ctu_stops_at_pv_and_ctud_down_stops_at_zero():
    # CTU PV 2: rising U at scans 0, 2, 4 give 1, 2, then 2 (stopped at PV, Bolton Fig. 10.1b).
    # CTUD PV 2 counting down only: rising D at scans 0 and 2 leave CV at 0 (Beckhoff CTUD).
    source = """PROGRAM S
VAR_INPUT U, D : BOOL; END_VAR
VAR_OUTPUT A, B : INT; QA, QB : BOOL; END_VAR
VAR C1 : CTU; C2 : CTUD; END_VAR
C1(CU := U, PV := 2);
C2(CD := D, PV := 2);
A := C1.CV; QA := C1.Q;
B := C2.CV; QB := C2.QD;
END_PROGRAM"""
    scans = trace(source, 6, U=[1, 0, 1, 0, 1, 0], D=[1, 0, 1, 0, 0, 0])
    assert [s["outputs"]["A"] for s in scans] == [1, 1, 2, 2, 2, 2]
    assert [s["outputs"]["QA"] for s in scans] == [False, False, True, True, True, True]
    assert [s["outputs"]["B"] for s in scans] == [0] * 6
    assert all(s["outputs"]["QB"] for s in scans)


def test_negative_preset_is_a_fault_with_position():
    result = run_program(timer_program("TON", 0).replace("T#0ms", "T#0ms - T#5ms"),
                         period_ms=PERIOD, duration_ms=200)
    assert result["status"] == "failed"
    assert result["diagnostics"][0]["code"] == "TIMER_PRESET"
    assert result["diagnostics"][0]["element_ref"]["field"] == "source:5:1"
